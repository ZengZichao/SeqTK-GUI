def default_text(option) -> str:
    if option.is_flag:
        return "`off`"
    if option.default is None or option.default == "":
        return "`unset`"
    return f"`{option.default}`"


def strip_flag_prefix(text: str) -> str:
    """Drop the leading ``-q INT    `` so the table columns are not repeated."""
    parts = text.split(None, 1)
    if len(parts) == 2 and parts[0].startswith("-"):
        rest = parts[1].split(None, 1)
        # "-q INT  mask bases ..." -> the type token belongs to the flag column.
        if rest and rest[0].upper() in ("INT", "FLOAT", "CHAR", "FILE", "STR"):
            return rest[1] if len(rest) > 1 else ""
        return parts[1]
    return text


def render(t: dict, language: str) -> str:
    period = "" if language == "zh" else "."
    lines = [t["title"], "", t["intro"], ""]
    for group in GROUPS:
        commands = [c for c in COMMANDS if c.group == group]
        if not commands:
            continue
        lines.append(t["group"][group])
        lines.append("")
        for command in commands:
            heading = f"### `{command.name}`"
            if not command.documented:
                heading += f" _({t['undocumented_tag']})_"
            lines.append(heading)
            lines.append("")
            lines.append((command.summary_zh if language == "zh" else command.summary_en)
                         + period)
            lines.append("")

            usage = ["seqtk", command.name]
            if command.options:
                usage.append("[options]")
            usage += [p.help_en if language == "en" else p.help_zh for p in command.positionals]
            lines.append("```text")
            lines.append(" ".join(usage))
            lines.append("```")
            lines.append("")

            if command.options:
                lines.append(f"**{t['options']}**")
                lines.append("")
                lines.append(f"| 标志 | {t['value']} | {t['default']} | 含义 |"
                             if language == "zh" else
                             f"| Flag | {t['value']} | {t['default']} | Meaning |")
                lines.append("| --- | --- | --- | --- |")
                for option in command.options:
                    value = t["flag"] if option.is_flag else option.value_kind
                    help_text = strip_flag_prefix(
                        option.help_zh if language == "zh" else option.help_en)
                    help_text = help_text.replace("|", "\\|")
                    lines.append(f"| `-{option.flag}` | {value} | {default_text(option)} "
                                 f"| {help_text} |")
                lines.append("")

            if command.positionals:
                lines.append(f"**{t['positional']}**")
                lines.append("")
                lines.append("| 参数 | 类型 | | 说明 |" if language == "zh"
                             else "| Argument | Type | | Description |")
                lines.append("| --- | --- | --- | --- |")
                for positional in command.positionals:
                    state = t["required"] if positional.required else t["optional"]
                    help_text = (positional.help_zh if language == "zh"
                                 else positional.help_en).replace("|", "\\|")
                    lines.append(f"| `{positional.key}` | `{positional.kind}` | {state} | {help_text} |")
                lines.append("")

            note = command.notes_zh if language == "zh" else command.notes_en
            if note:
                lines.append(f"**{t['notes']}**: {note}")
                lines.append("")
    lines.append(f"## {t['source']}")
    lines.append("")
    lines.append(t["source_body"])
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    docs = ROOT / "docs"
    docs.mkdir(exist_ok=True)
    (docs / "COMMANDS.md").write_text(render(EN, "en"), encoding="utf-8", newline="\n")
    (docs / "COMMANDS.zh-CN.md").write_text(render(ZH, "zh"), encoding="utf-8", newline="\n")
    print("wrote docs/COMMANDS.md and docs/COMMANDS.zh-CN.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
